const Shell = require('../js/shell.js');
let fails = 0;
function t(name, cond){ if(!cond){ fails++; console.log('FAIL', name);} else console.log('ok  ', name); }
const s = new Shell();
const r = (l)=>s.run(l);
t('pwd', r('pwd').out === '/home/hocvien\n');
t('ls', r('ls').out.includes('ghichu.txt') && !r('ls').out.includes('.cauhinh'));
t('ls -a hidden', r('ls -a').out.includes('.cauhinh'));
t('mkdir+cd', (r('mkdir linux-lab'), r('cd linux-lab'), s.cwd === '/home/hocvien/linux-lab'));
t('echo >', (r('echo hello > nhatky.txt'), s.readFile('nhatky.txt') === 'hello\n'));
t('echo >>', (r('echo world >> nhatky.txt'), s.readFile('nhatky.txt') === 'hello\nworld\n'));
t('cp', (r('cp nhatky.txt backup.txt'), s.readFile('backup.txt') === 'hello\nworld\n'));
t('mv rename', (r('mv nhatky.txt nhatky-cu.txt'), !s.exists('nhatky.txt') && s.exists('nhatky-cu.txt')));
t('mv into dir', (r('mkdir d'), r('mv backup.txt d'), s.exists('d/backup.txt')));
t('cp -r', (r('cp -r d d2'), s.exists('d2/backup.txt')));
t('cp dir no -r', r('cp d d3').err.includes('-r not specified'));
t('rm dir needs -r', r('rm d').err.includes('Is a directory'));
t('rm -r', (r('rm -r d d2'), !s.exists('d') && !s.exists('d2')));
t('rm missing', r('rm nope').err.includes('No such file'));
t('rm -rf ~ blocked', r('rm -rf ~').err.includes('dangerous') && s.exists('/home/hocvien/ghichu.txt'));
t('glob', (r('touch a1.txt a2.txt b.log'), r('ls a*.txt').out.trim() === 'a1.txt  a2.txt'));
t('rm glob', (r('rm a*.txt'), !s.exists('a1.txt')));
t('chmod 755', (r('touch x.sh'), r('chmod 755 x.sh'), s.node('x.sh').mode === 0o755));
t('chmod u+x', (r('touch y.sh'), r('chmod u+x y.sh'), s.node('y.sh').mode === 0o744));
t('chmod go-r', (r('chmod go-r y.sh'), s.node('y.sh').mode === 0o700));
t('ls -l perms', r('ls -l y.sh').out.startsWith('-rwx------'));
t('pipe grep wc', (r('echo ERROR a > l.txt'), r('echo ok >> l.txt'), r('echo ERROR b >> l.txt'), r('cat l.txt | grep ERROR | wc -l').out.trim() === '2'));
t('grep > file', (r('grep ERROR l.txt > loi.txt'), s.readFile('loi.txt') === 'ERROR a\nERROR b\n'));
t('head', r('head -n 1 l.txt').out === 'ERROR a\n');
t('tail', r('tail -n 1 l.txt').out === 'ERROR b\n');
t('quotes', (r('echo "a   b" > q.txt'), s.readFile('q.txt') === 'a   b\n'));
t('unknown', r('foo').err.includes('command not found'));
t('cd missing', r('cd zzz').err.includes('No such file'));
t('cd ..', (r('cd ..'), s.cwd === '/home/hocvien'));
t('cd ~ and -', (r('cd /tmp'), r('cd ~'), s.cwd === '/home/hocvien'));
t('prompt', s.prompt() === 'hocvien@linux-lab:~$ ');
t('complete cmd', s.complete('mkd').cands[0] === 'mkdir');
t('complete file', s.complete('cat gh').cands[0] === 'ghichu.txt');
t('perm denied read', (r('chmod 000 ghichu.txt'), r('cat ghichu.txt').err.includes('Permission denied')));
t('write to non-existing dir', r('echo a > nodir/x').err.includes('No such file'));
t('dir x perm blocks cd', (r('mkdir secret'), r('chmod 000 secret'), r('cd secret').err.includes('Permission denied')));
t('dir r perm blocks ls', r('ls secret').err.includes('Permission denied'));
t('dir chmod 700 unlocks cd', (r('chmod 700 secret'), r('cd secret'), s.cwd === '/home/hocvien/secret', r('cd ..')));
t('chain && success', (r('mkdir cdir && touch cdir/ok.txt'), s.exists('cdir/ok.txt')));
t('chain && stops on fail', (r('cd nonexist && touch cdir/bad.txt'), !s.exists('cdir/bad.txt')));
t('chain || runs on fail', r('cd nonexist || echo fallback').out.includes('fallback'));
t('find -name', r('find . -name "*.txt"').out.includes('ghichu.txt'));
t('tar -czf and -tzf', (r('tar -czf pack.tar.gz Documents'), s.exists('pack.tar.gz') && r('tar -tzf pack.tar.gz').out.includes('baocao.txt')));
t('df -h and free -h', r('df -h').out.includes('Filesystem') && r('free -h').out.includes('Mem:'));
t('ps aux and pgrep', r('ps aux').out.includes('sshd') && r('pgrep -c nginx').out.trim() === '2');
t('systemctl and sudo', (r('systemctl stop nginx').err.includes('Access denied'), r('sudo systemctl stop nginx'), r('systemctl is-active nginx').out.trim() === 'inactive', r('sudo systemctl start nginx'), r('systemctl is-active nginx').out.trim() === 'active'));
t('journalctl -u nginx', r('journalctl -u nginx').out.includes('nginx'));
t('ip a and ping', r('ip a').out.includes('192.168.1.50') && r('ping -c 2 8.8.8.8').out.includes('bytes from'));
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
process.exit(fails?1:0);
